async function seedAll() {
  try {
    await connectDB();
    console.log(`Connecting to MongoDB Atlas to seed ${productsToSeed.length} products...`);

    let upsertedCount = 0;
    for (const prod of productsToSeed) {
      await Product.findOneAndUpdate(
        { slug: prod.slug },
        prod,
        { upsert: true, returnDocument: "after" }
      );
      upsertedCount++;
    }
    console.log(`Successfully upserted ${upsertedCount} verified products without dropping collections!`);

    // Verify product counts by category
    const stats = await Product.aggregate([
      { $group: { _id: "$category", count: { $sum: 1 } } },
      { $sort: { count: -1 } }
    ]);
    console.log("\nUpdated Product Counts per Category in Atlas:");
    console.log(JSON.stringify(stats, null, 2));

    const total = await Product.countDocuments();
    console.log(`\nGrand Total Products in MongoDB Atlas: ${total}`);
    process.exit(0);
  } catch (err) {
    console.error("Seeding failed:", err.message);
    process.exit(1);
  }
}

seedAll();


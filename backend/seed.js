const seedDatabase = async () => {
  try {
    await connectDB();
    console.log("Seeding ShopNest database...");

    // 1. Seed or update products
    for (const prodData of sampleProducts) {
      await Product.findOneAndUpdate(
        { slug: prodData.slug },
        prodData,
        { upsert: true, new: true, setDefaultsOnInsert: true }
      );
    }
    console.log(`Seeded ${sampleProducts.length} high-quality products.`);

    // 2. Seed default Administrator
    const adminEmail = "admin@shopnest.com";
    const existingAdmin = await User.findOne({ email: adminEmail });
    if (!existingAdmin) {
      await User.create({
        name: "ShopNest Administrator",
        email: adminEmail,
        password: "Admin@123456",
        role: "admin",
        phone: "9876543210",
      });
      console.log("Created default Admin account: admin@shopnest.com / Admin@123456");
    } else {
      console.log("Admin account already exists.");
    }

    // 3. Seed default Customer
    const customerEmail = "customer@shopnest.com";
    const existingCustomer = await User.findOne({ email: customerEmail });
    if (!existingCustomer) {
      await User.create({
        name: "Rahul Sharma",
        email: customerEmail,
        password: "Customer@123456",
        role: "customer",
        phone: "9123456780",
        addresses: [
          {
            fullName: "Rahul Sharma",
            phone: "9123456780",
            addressLine: "Flat 402, Sunshine Heights, Linking Road",
            city: "Mumbai",
            state: "Maharashtra",
            postalCode: "400050",
            country: "India",
            isDefault: true,
          },
        ],
      });
      console.log("Created demo customer: customer@shopnest.com / Customer@123456");
    }

    // 4. Seed active coupons
    for (const coup of sampleCoupons) {
      await Coupon.findOneAndUpdate(
        { code: coup.code },
        coup,
        { upsert: true, new: true }
      );
    }
    console.log(`Seeded ${sampleCoupons.length} promotional coupons (SAVE10, SHOP500, FESTIVE50).`);

    console.log("ShopNest database seeding completed successfully!");
    process.exit(0);
  } catch (err) {
    console.error("Database seeding failed:", err);
    process.exit(1);
  }
};

